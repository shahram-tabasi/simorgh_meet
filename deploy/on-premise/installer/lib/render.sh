render_configs() {
  local url; url=$(public_url)
  install -d -m 0755 "$SIMORGH_HOME/config/nginx-custom" "$SIMORGH_HOME/config/postgres-init"
  local port_suffix=''; [ "$HTTPS_PORT" = 443 ] || port_suffix=":$HTTPS_PORT"
  sed "s|@@HTTPS_PORT_SUFFIX@@|${port_suffix}|g" "$BUNDLE_DIR/templates/nginx-custom/simorgh.conf" \
    >"$SIMORGH_HOME/config/nginx-custom/simorgh.conf"
  chmod 0644 "$SIMORGH_HOME/config/nginx-custom/simorgh.conf"
  install -m 0755 "$BUNDLE_DIR/templates/postgres-init/10-keycloak.sh" "$SIMORGH_HOME/config/postgres-init/10-keycloak.sh"

  install -d -m 0755 "$SIMORGH_HOME/config/jigasi"
  install -m 0755 "$BUNDLE_DIR/templates/jigasi/11-simorgh-transcripts" "$SIMORGH_HOME/config/jigasi/11-simorgh-transcripts"

  install -d -m 0750 "$SIMORGH_HOME/config/keycloak"
  if [ "${ENABLE_IDP:-0}" = 1 ] && [ ! -f "$SIMORGH_HOME/config/keycloak/.imported" ]; then
    # Realm import only creates missing realms, so this is safe to re-render.
    sed -e "s|@@PUBLIC_URL@@|$(sed_escape "$url")|g" \
        -e "s|@@ORGANIZATION_NAME@@|$(sed_escape "$(json_escape "$ORGANIZATION_NAME")")|g" \
        -e "s|@@ADMIN_USERNAME@@|$(sed_escape "$ADMIN_USERNAME")|g" \
        -e "s|@@ADMIN_EMAIL@@|$(sed_escape "$ADMIN_EMAIL")|g" \
        -e "s|@@ADMIN_DISPLAY_NAME@@|$(sed_escape "$(json_escape "$ADMIN_DISPLAY_NAME")")|g" \
        -e "s|@@ADMIN_PASSWORD@@|$(sed_escape "$(json_escape "$ADMIN_PASSWORD")")|g" \
        "$BUNDLE_DIR/templates/keycloak/simorgh-realm.json.tmpl" >"$SIMORGH_HOME/config/keycloak/simorgh-realm.json"
    chmod 600 "$SIMORGH_HOME/config/keycloak/simorgh-realm.json"
    # Keycloak runs as uid 1000 inside the container.
    chown -R 1000:0 "$SIMORGH_HOME/config/keycloak"
  fi

  install -d -m 0755 "$DATA_DIR" "$DATA_DIR/postgres" "$DATA_DIR/stt" "$DATA_DIR/minutes" "$DATA_DIR/backups" \
    "$DATA_DIR/jitsi" "$DATA_DIR/jitsi/web/keys" "$DATA_DIR/jitsi/transcripts" "$DATA_DIR/jitsi/jibri/recordings"
  # The AI containers run as the unprivileged uid 10001 (see services/ai/Dockerfile).
  chown -R 10001:10001 "$DATA_DIR/stt" "$DATA_DIR/minutes"
}

# envq VALUE -> single-quoted value for docker compose .env files (literal, no interpolation)
envq() { printf "'%s'" "$(printf '%s' "$1" | sed "s/'/’/g")"; }

sed_escape()  { printf '%s' "$1" | sed -e 's/[\/&|]/\\&/g'; }
json_escape() { printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'; }

# ------------------------------------------------------------------ certificates
render_certificates() {
  local keys="$DATA_DIR/jitsi/web/keys" pki="$SIMORGH_HOME/pki"
  install -d -m 0755 "$keys"; install -d -m 0700 "$pki"
  if [ "$TLS_MODE" = custom ]; then
    install -m 0644 "$TLS_CERT_FILE" "$keys/cert.crt"
    install -m 0600 "$TLS_KEY_FILE" "$keys/cert.key"
    ok "Installed organization certificate"
    return
  fi
  if [ -f "$keys/cert.crt" ] && [ -f "$pki/server.san" ] && [ "$(cat "$pki/server.san")" = "$(cert_san)" ]; then
    ok "Existing self-signed certificate kept"
    return
  fi
  if have openssl; then
    generate_certs_openssl "$pki"
  else
    info "openssl not found on host; generating certificates inside the bundled AI image"
    docker run --rm -v "$pki:/pki" --entrypoint python "simorgh-meet/ai:${BUNDLE_VERSION}" \
      -m simorgh_ai.tlsgen --out /pki --cn "$PUBLIC_HOST" --san "$(cert_san)" --org "$ORGANIZATION_NAME" \
      >>"$LOG_FILE" 2>&1 || die "certificate generation failed"
  fi
  install -m 0644 "$pki/server.crt" "$keys/cert.crt"
  install -m 0600 "$pki/server.key" "$keys/cert.key"
  cert_san >"$pki/server.san"
  install -m 0644 "$pki/ca.crt" "$SIMORGH_HOME/simorgh-meet-ca.crt"
  ok "Self-signed certificate created. Distribute $SIMORGH_HOME/simorgh-meet-ca.crt to client devices."
}

cert_san() {
  local san="DNS:localhost,IP:127.0.0.1"
  if is_ipv4 "$PUBLIC_HOST"; then san="$san,IP:$PUBLIC_HOST"; else san="$san,DNS:$PUBLIC_HOST"; fi
  [ "$LAN_IP" != "$PUBLIC_HOST" ] && san="$san,IP:$LAN_IP"
  [ -n "${PUBLIC_IP:-}" ] && [ "$PUBLIC_IP" != "$LAN_IP" ] && [ "$PUBLIC_IP" != "$PUBLIC_HOST" ] && san="$san,IP:$PUBLIC_IP"
  printf '%s' "$san"
}

generate_certs_openssl() {
  local pki=$1
  if [ ! -f "$pki/ca.key" ]; then
    openssl req -x509 -newkey rsa:3072 -sha256 -days 3650 -nodes \
      -keyout "$pki/ca.key" -out "$pki/ca.crt" \
      -subj "/O=Simorgh Meet/CN=Simorgh Meet Local CA ($(hostname -s))" \
      -addext "basicConstraints=critical,CA:TRUE" -addext "keyUsage=critical,keyCertSign,cRLSign" \
      >>"$LOG_FILE" 2>&1 || die "CA generation failed"
  fi
  openssl req -newkey rsa:2048 -sha256 -nodes -keyout "$pki/server.key" -out "$pki/server.csr" \
    -subj "/O=Simorgh Meet/CN=${PUBLIC_HOST}" >>"$LOG_FILE" 2>&1 || die "CSR generation failed"
  printf 'basicConstraints=CA:FALSE\nkeyUsage=critical,digitalSignature,keyEncipherment\nextendedKeyUsage=serverAuth\nsubjectAltName=%s\n' \
    "$(cert_san)" >"$pki/server.ext"
  openssl x509 -req -in "$pki/server.csr" -CA "$pki/ca.crt" -CAkey "$pki/ca.key" -CAcreateserial \
    -days 825 -sha256 -extfile "$pki/server.ext" -out "$pki/server.crt" >>"$LOG_FILE" 2>&1 \
    || die "certificate signing failed"
  cat "$pki/ca.crt" >>"$pki/server.crt"   # serve the full chain
  chmod 600 "$pki"/*.key
}

# ------------------------------------------------------------------ answers file
save_answers() {
  # Non-secret answers for re-runs/upgrades (passwords are never written here).
  local f="$SIMORGH_HOME/install-answers.env" v
  : >"$f"; chmod 600 "$f"
  for v in PUBLIC_HOST LAN_IP HTTPS_PORT HTTP_PORT JVB_PORT EXTERNAL_GUESTS PUBLIC_IP ENABLE_TURN TLS_MODE \
           TLS_CERT_FILE TLS_KEY_FILE ORGANIZATION_NAME TZ ADMIN_USERNAME ADMIN_EMAIL ADMIN_DISPLAY_NAME \
           MEET_AUTH_MODE ENABLE_RECORDING RECORDING_RETENTION_DAYS ENABLE_AI ENABLE_IDP DATA_DIR \
           STT_WORKERS STT_CPU_THREADS STT_CPU_LIMIT LLM_THREADS LLM_CPU_LIMIT LLM_CONTEXT LLM_CHUNK_CHARS; do
    printf '%s=%q\n' "$v" "${!v:-}" >>"$f"
  done
}
