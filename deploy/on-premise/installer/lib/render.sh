# shellcheck shell=bash
# Render runtime configuration from wizard answers. Secrets are generated once and
# preserved on re-install/upgrade (read back from the existing .env).

SECRET_VARS="POSTGRES_PASSWORD KEYCLOAK_DB_PASSWORD KEYCLOAK_ADMIN_PASSWORD JICOFO_AUTH_PASSWORD
JVB_AUTH_PASSWORD JIGASI_XMPP_PASSWORD JIGASI_TRANSCRIBER_PASSWORD JIBRI_RECORDER_PASSWORD
JIBRI_XMPP_PASSWORD JWT_APP_SECRET TURN_SECRET"

load_existing_secrets() {
  local env_file="$SIMORGH_HOME/.env" v line
  [ -f "$env_file" ] || return 0
  for v in $SECRET_VARS; do
    line=$(grep -E "^${v}=" "$env_file" | tail -n1) || true
    [ -n "$line" ] && printf -v "$v" '%s' "${line#*=}"
  done
  return 0
}

ensure_secrets() {
  local v
  for v in $SECRET_VARS; do
    [ -n "${!v:-}" ] || printf -v "$v" '%s' "$(random_secret 32)"
  done
}

public_url() {
  if [ "$HTTPS_PORT" = 443 ]; then printf 'https://%s' "$PUBLIC_HOST"; else printf 'https://%s:%s' "$PUBLIC_HOST" "$HTTPS_PORT"; fi
}

compose_profiles() {
  local p=()
  [ "${ENABLE_RECORDING:-0}" = 1 ] && p+=(recording)
  [ "${ENABLE_AI:-0}" = 1 ] && p+=(ai)
  [ "${ENABLE_IDP:-0}" = 1 ] && p+=(idp)
  [ "${ENABLE_TURN:-0}" = 1 ] && p+=(turn)
  local IFS=,; printf '%s' "${p[*]}"
}

