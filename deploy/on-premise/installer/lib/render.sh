  local auth_type=internal guests=1 jwt_block=''
  if [ "$MEET_AUTH_MODE" = jwt ]; then
    auth_type=jwt; guests=0
    jwt_block="JWT_APP_ID=simorgh-meet
JWT_APP_SECRET=${JWT_APP_SECRET}
JWT_ACCEPTED_ISSUERS=simorgh-meet
