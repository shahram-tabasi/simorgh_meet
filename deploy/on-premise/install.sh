#!/usr/bin/env bash
# Simorgh Meet — offline On-Premise installer (نصب‌کننده آفلاین سیمرغ میت)
#
# Usage (from the extracted bundle, or via the self-extracting .run file):
#   sudo ./install.sh                       interactive install / re-configure
#   sudo ./install.sh --answers FILE        unattended (values from FILE, see answers.example.env)
#   sudo ./install.sh --upgrade             reuse saved answers + secrets, load new images
#   sudo ./install.sh --prefix /opt/simorgh-meet --skip-docker --no-start
set -Eeuo pipefail

BUNDLE_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
SIMORGH_HOME=/opt/simorgh-meet
ANSWERS_FILE=''
UPGRADE=0
SKIP_DOCKER=0
NO_START=0
SKIP_VERIFY=0

# shellcheck source=installer/lib/common.sh
. "$BUNDLE_DIR/installer/lib/common.sh"
# shellcheck source=installer/lib/docker.sh
. "$BUNDLE_DIR/installer/lib/docker.sh"
# shellcheck source=installer/lib/wizard.sh
. "$BUNDLE_DIR/installer/lib/wizard.sh"
# shellcheck source=installer/lib/render.sh
. "$BUNDLE_DIR/installer/lib/render.sh"

usage() { sed -n '2,9p' "$0" | sed 's/^# \{0,1\}//'; exit 0; }

while [ $# -gt 0 ]; do
  case $1 in
    --answers) ANSWERS_FILE=$2; NONINTERACTIVE=1; shift 2 ;;
    --upgrade) UPGRADE=1; shift ;;
    --prefix) SIMORGH_HOME=$2; shift 2 ;;
    --skip-docker) SKIP_DOCKER=1; shift ;;
    --no-start) NO_START=1; shift ;;
    --skip-verify) SKIP_VERIFY=1; shift ;;
    -h|--help) usage ;;
    *) die "Unknown option: $1" ;;
  esac
done

trap 'die "Installation failed at line $LINENO. Details: $LOG_FILE"' ERR

banner() {
  cat <<'EOF'

   ╔══════════════════════════════════════════════════════════╗
   ║   Simorgh Meet — سامانه جلسات سازمانی سیمرغ (On-Premise)   ║
   ╚══════════════════════════════════════════════════════════╝
EOF
}

load_manifest() {
  [ -f "$BUNDLE_DIR/manifest.env" ] || die "manifest.env missing — is this a complete bundle?"
  # manifest.env is generated by tools/package/build-bundle.sh: plain KEY=VALUE lines.
  while IFS='=' read -r k v; do
    [[ $k =~ ^[A-Z_][A-Z0-9_]*$ ]] || continue
    printf -v "$k" '%s' "$v"
  done <"$BUNDLE_DIR/manifest.env"
  info "Bundle ${BUNDLE_VERSION} (Jitsi ${JITSI_IMAGE_VERSION}, STT ${STT_MODEL_DIR:-none}, LLM ${LLM_MODEL_FILE:-none})"
}

verify_bundle() {
  [ "$SKIP_VERIFY" = 1 ] && { warn "Checksum verification skipped"; return; }
  [ -f "$BUNDLE_DIR/SHA256SUMS" ] || die "SHA256SUMS missing"
  info "Verifying bundle integrity (this reads every file once)…"
  (cd "$BUNDLE_DIR" && sha256sum --quiet -c SHA256SUMS) >>"$LOG_FILE" 2>&1 \
    || die "Bundle is corrupted (checksum mismatch). Re-copy the installer."
  ok "Bundle integrity verified"
}

preflight() {
  step "Preflight checks / بررسی پیش‌نیازها"
  [ "$(uname -s)" = Linux ] || die "Linux is required"
  [ "$(uname -m)" = x86_64 ] || die "x86_64 (amd64) CPU is required; detected $(uname -m)"
  have systemctl || die "systemd is required"
  local kmaj kmin; IFS=. read -r kmaj kmin _ <<<"$(uname -r)"
  { [ "$kmaj" -gt 4 ] || { [ "$kmaj" -eq 4 ] && [ "$kmin" -ge 18 ]; }; } || die "Linux kernel >= 4.18 required"
  local cores mem; cores=$(cpu_cores); mem=$(mem_total_gb)
  info "CPU cores: $cores, RAM: ${mem} GB, kernel $(uname -r)"
  [ "$cores" -ge 4 ] || die "At least 4 CPU cores are required"
  [ "$mem" -ge 8 ] || die "At least 8 GB RAM is required"
  cpu_has avx2 || warn "CPU lacks AVX2: speech recognition and the AI model will be much slower"
  local need=$(( $(du -sm "$BUNDLE_DIR" | awk '{print $1}') / 1024 + 20 ))
  [ "$(disk_free_gb "$SIMORGH_HOME")" -ge "$need" ] || die "Need ~${need} GB free for $SIMORGH_HOME"
  if [ "$UPGRADE" != 1 ]; then
    local p
    for p in "${HTTPS_PORT:-443}" "${HTTP_PORT:-80}"; do
      port_in_use "$p" tcp && warn "TCP port $p is already in use by another service"
    done
    port_in_use "${JVB_PORT:-10000}" udp && warn "UDP port ${JVB_PORT:-10000} is already in use"
  fi
  if have getenforce && [ "$(getenforce 2>/dev/null)" = Enforcing ]; then
    warn "SELinux is enforcing; volumes are labelled by compose (:Z) but review audit logs if services fail"
  fi
  ok "Preflight passed"
}

copy_payload() {
  step "Installing files / نصب فایل‌ها"
  install -d -m 0755 "$SIMORGH_HOME" "$SIMORGH_HOME/compose" "$SIMORGH_HOME/bin" "$SIMORGH_HOME/models"
  cp -a "$BUNDLE_DIR/compose/." "$SIMORGH_HOME/compose/"
  install -m 0755 "$BUNDLE_DIR/bin/simorgh-meet" "$SIMORGH_HOME/bin/simorgh-meet"
  install -m 0644 "$BUNDLE_DIR/installer/lib/common.sh" "$SIMORGH_HOME/bin/common.sh"
  ln -sf "$SIMORGH_HOME/bin/simorgh-meet" /usr/local/bin/simorgh-meet
  install -m 0644 "$BUNDLE_DIR/manifest.env" "$SIMORGH_HOME/manifest.env"
  if [ -d "$BUNDLE_DIR/models" ]; then
    info "Copying AI models (several GB)…"
    cp -a --no-preserve=ownership "$BUNDLE_DIR/models/." "$SIMORGH_HOME/models/"
    chmod -R a+rX "$SIMORGH_HOME/models"
  fi
  install -m 0644 "$BUNDLE_DIR/systemd/simorgh-meet.service" /etc/systemd/system/simorgh-meet.service
  install -m 0644 "$BUNDLE_DIR/systemd/simorgh-meet-maintenance.service" /etc/systemd/system/
  install -m 0644 "$BUNDLE_DIR/systemd/simorgh-meet-maintenance.timer" /etc/systemd/system/
  systemctl daemon-reload
  systemctl enable simorgh-meet.service simorgh-meet-maintenance.timer >>"$LOG_FILE" 2>&1
  ok "Files installed to $SIMORGH_HOME"
}

finish_identity() {
  [ "${ENABLE_IDP:-0}" = 1 ] || return 0
  local realm="$SIMORGH_HOME/config/keycloak/simorgh-realm.json"
  [ -f "$realm" ] || return 0
  # Keycloak imports only at container start; recreate it so a pending realm file is read
  # (an unchanged container would not restart on re-install).
  "$SIMORGH_HOME/bin/simorgh-meet" compose up -d --force-recreate --no-deps keycloak >>"$LOG_FILE" 2>&1
  info "Waiting for the identity server to import the realm…"
  # health/ready turns UP before the bootstrap import finishes, so wait for the realm itself.
  local probe='exec 3<>/dev/tcp/127.0.0.1/8080 && printf "GET /auth/realms/simorgh/.well-known/openid-configuration HTTP/1.0\r\nHost: localhost\r\n\r\n" >&3 && head -n1 <&3 | grep -q " 200 "'
  for _ in $(seq 1 120); do
    if "$SIMORGH_HOME/bin/simorgh-meet" compose exec -T keycloak bash -c "$probe" >/dev/null 2>&1; then
      # The realm file holds the initial admin password; remove it once imported.
      shred -u "$realm" 2>/dev/null || rm -f "$realm"
      touch "$SIMORGH_HOME/config/keycloak/.imported"
      ok "Identity server ready (realm 'simorgh' imported)"
      return 0
    fi
    sleep 5
  done
  warn "Identity server not ready yet; check: simorgh-meet logs keycloak"
}

create_meeting_admin() {
  [ "$MEET_AUTH_MODE" = internal ] || return 0
  "$SIMORGH_HOME/bin/simorgh-meet" user add "$ADMIN_USERNAME" "$ADMIN_PASSWORD" >>"$LOG_FILE" 2>&1 \
    && ok "Meeting host account '$ADMIN_USERNAME' created" \
    || warn "Could not create host account now; run: simorgh-meet user add $ADMIN_USERNAME"
}

write_credentials() {
  local f="$SIMORGH_HOME/credentials.txt" url; url=$(public_url)
  umask 077
  cat >"$f" <<EOF
Simorgh Meet — initial credentials (delete this file after storing them safely)
=============================================================================
Meeting URL            : ${url}
Host / admin username  : ${ADMIN_USERNAME}
Host / admin password  : ${ADMIN_PASSWORD}
EOF
  if [ "${ENABLE_IDP:-0}" = 1 ]; then
    cat >>"$f" <<EOF
Identity console       : ${url}/auth/admin/   (user: kcadmin, password: ${KEYCLOAK_ADMIN_PASSWORD})
Realm login            : ${url}/auth/realms/simorgh/account/  (password change required at first login)
EOF
  fi
  umask 022
}

main() {
  banner
  require_root
  install -d -m 0755 "$(dirname "$LOG_FILE")"; : >>"$LOG_FILE"; chmod 600 "$LOG_FILE"
  load_manifest
  if [ "$UPGRADE" = 1 ] || [ -f "$SIMORGH_HOME/install-answers.env" ]; then
    # Previous answers become defaults (or the actual values with --upgrade).
    # shellcheck disable=SC1091
    [ -f "$SIMORGH_HOME/install-answers.env" ] && . "$SIMORGH_HOME/install-answers.env"
    # shellcheck disable=SC2034  # read by the sourced prompt helpers
    [ "$UPGRADE" = 1 ] && NONINTERACTIVE=1
  fi
  if [ -n "$ANSWERS_FILE" ]; then
    # shellcheck disable=SC1090
    . "$ANSWERS_FILE"
  fi
  preflight
  verify_bundle

  if [ "$UPGRADE" = 1 ]; then
    [ -f "$SIMORGH_HOME/.env" ] || die "--upgrade requires an existing installation in $SIMORGH_HOME"
    compute_sizing "$(cpu_cores)" "$(mem_total_gb)"
    ADMIN_PASSWORD=${ADMIN_PASSWORD:-unchanged}
  else
    wizard
  fi

  step "Container engine / موتور کانتینر"
  if [ "$SKIP_DOCKER" = 1 ]; then
    docker_installed_ok || die "--skip-docker given but no working Docker >= ${DOCKER_MIN_MAJOR} found"
    compose_installed_ok || install_compose_plugin "$BUNDLE_DIR"
  else
    ensure_docker "$BUNDLE_DIR"
  fi

  step "Loading application images (offline) / بارگذاری ایمیج‌ها"
  load_images "$BUNDLE_DIR"

  copy_payload

  step "Configuration / پیکربندی"
  load_existing_secrets
  ensure_secrets
  render_env
  render_configs
  render_certificates
  save_answers
  ok "Configuration written to $SIMORGH_HOME/.env"

  if [ "$NO_START" = 1 ]; then
    ok "Installed. Start later with: simorgh-meet up"
    return
  fi

  step "Starting services / راه‌اندازی سرویس‌ها"
  "$SIMORGH_HOME/bin/simorgh-meet" up
  "$SIMORGH_HOME/bin/simorgh-meet" wait-healthy || warn "Some services are still starting; check: simorgh-meet status"
  if [ "$UPGRADE" != 1 ]; then
    finish_identity
    create_meeting_admin
    write_credentials
  fi

  step "Done / پایان"
  cat <<EOF
  ${C_GREEN}Simorgh Meet is running.${C_RESET}  آدرس: $(public_url)

  • Credentials        : $SIMORGH_HOME/credentials.txt (root only)
  • Manage             : simorgh-meet status | logs | backup | restore | user add | upgrade
  • Firewall           : allow TCP ${HTTP_PORT}, ${HTTPS_PORT} and UDP ${JVB_PORT} to this server$( [ "${ENABLE_TURN:-0}" = 1 ] && echo ", plus TCP/UDP 3478 and UDP 49160-49200 (TURN)")
EOF
  [ "$TLS_MODE" = self-signed ] && cat <<EOF
  • Certificate        : install $SIMORGH_HOME/simorgh-meet-ca.crt as a trusted root on client devices
EOF
  [ "${ENABLE_AI:-0}" = 1 ] && cat <<EOF
  • AI minutes         : start "Transcription / رونویسی" or record the meeting.
                         After processing, download text at $(public_url)/simorgh-archive/.
  • Archive credentials: $SIMORGH_HOME/archive-credentials.txt (root only)
EOF
  return 0
}

main "$@"
